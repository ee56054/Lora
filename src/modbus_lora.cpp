static uint16_t crc16(const uint8_t *buffer, uint16_t buffer_length) {
    uint8_t crc_hi = 0xFF; /* high CRC byte initialized */
    uint8_t crc_lo = 0xFF; /* low CRC byte initialized */
    unsigned int i;

    while (buffer_length--) {
        i = crc_lo ^ *buffer++;
        crc_lo = crc_hi ^ table_crc_hi[i];
        crc_hi = table_crc_lo[i];
    }

    return (crc_hi << 8 | crc_lo);
}

static int _modbus_lora_send_msg_pre(uint8_t *req, int req_length) {
    uint16_t crc = crc16(req, req_length);
    req[req_length++] = crc & 0x00FF; // Low byte first
    req[req_length++] = crc >> 8;     // High byte second
    return req_length;
}

